#!/usr/bin/env node
/**
 * Generates eslint/logician-exports.json — the name sets the
 * `logician/no-chakra-import` rule reads — from logician-ui's real public
 * surface, so the rule cannot drift from what the package exports.
 *
 *   own          names src/index.ts exports that logician-ui implements itself
 *                (a consumer importing these from @chakra-ui/react is picking
 *                the raw Chakra component over the DS one)
 *   passthrough  names re-exported unchanged from @chakra-ui/react via
 *                src/chakra.ts (the explicit allowlist)
 *
 * Each set is split into `values` and `types` (type-only exports), computed
 * with the TypeScript checker — not by regex — so `export *` chains and
 * `export type { … }` are resolved exactly as consumers see them.
 *
 * It also fails if a pass-through name does not reach the package root as the
 * Chakra symbol (i.e. a logician export of the same name shadows it).
 *
 *   node scripts/eslint/generate-exports.cjs          # write the JSON
 *   node scripts/eslint/generate-exports.cjs --check  # exit 1 if it is stale
 *
 * `yarn check-exports` (part of `yarn lint`) runs the --check form.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const ROOT = path.resolve(__dirname, '../..');
const INDEX = path.join(ROOT, 'src/index.ts');
const CHAKRA = path.join(ROOT, 'src/chakra.ts');
const OUT = path.join(ROOT, 'eslint/logician-exports.json');

function loadProgram() {
  const configPath = path.join(ROOT, 'tsconfig.json');
  const parsed = ts.getParsedCommandLineOfConfigFile(
    configPath,
    {},
    {
      ...ts.sys,
      onUnRecoverableConfigFileDiagnostic(d) {
        throw new Error(ts.flattenDiagnosticMessageText(d.messageText, '\n'));
      },
    }
  );
  return ts.createProgram([INDEX], { ...parsed.options, noEmit: true });
}

function moduleExports(checker, program, file) {
  const sf = program.getSourceFile(file);
  if (!sf) throw new Error(`cannot load ${path.relative(ROOT, file)}`);
  const mod = checker.getSymbolAtLocation(sf);
  const map = new Map();
  for (const sym of checker.getExportsOfModule(mod)) {
    const target =
      sym.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(sym) : sym;
    map.set(sym.name, target);
  }
  return map;
}

const isValue = (sym) => (sym.flags & ts.SymbolFlags.Value) !== 0;
const sorted = (arr) => [...arr].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

function split(entries) {
  const values = [];
  const types = [];
  for (const [name, sym] of entries) (isValue(sym) ? values : types).push(name);
  return { values: sorted(values), types: sorted(types) };
}

function generate() {
  const program = loadProgram();
  const checker = program.getTypeChecker();
  const root = moduleExports(checker, program, INDEX);
  const pass = moduleExports(checker, program, CHAKRA);

  const errors = [];
  for (const [name, sym] of pass) {
    if (root.get(name) !== sym) {
      errors.push(
        `'${name}' is in src/chakra.ts but the package root exports a different '${name}' ` +
          `(logician-ui already has its own) — remove it from the pass-through list.`
      );
    }
  }
  if (errors.length) {
    const err = new Error(errors.join('\n'));
    err.collisions = true;
    throw err;
  }

  const own = [...root].filter(([name]) => !pass.has(name));
  return {
    $comment:
      'GENERATED by scripts/eslint/generate-exports.cjs from src/index.ts and src/chakra.ts — do not edit. Run `yarn check-exports`.',
    own: split(own),
    passthrough: split(pass),
    chakraTypes: chakraTypeNames(checker, program),
  };
}

/**
 * Names @chakra-ui/react exports as types only. Consumers often import types
 * without the `type` keyword (`import { TabsListProps } from …`); the rule
 * uses this list to treat those as type imports too, so a Chakra type with no
 * logician export is not reported. Informational: it tracks the installed
 * Chakra version, so `--check` ignores it (a Chakra bump must not fail lint).
 */
function chakraTypeNames(checker, program) {
  const sf = program.getSourceFile(CHAKRA);
  const decl = sf.statements.find(
    (s) =>
      (ts.isExportDeclaration(s) || ts.isImportDeclaration(s)) &&
      s.moduleSpecifier &&
      s.moduleSpecifier.text === '@chakra-ui/react'
  );
  const mod = checker.getSymbolAtLocation(decl.moduleSpecifier);
  const names = [];
  for (const sym of checker.getExportsOfModule(mod)) {
    const target =
      sym.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(sym) : sym;
    if (!isValue(target)) names.push(sym.name);
  }
  return sorted(names);
}

/** The part of the data that must match logician-ui's exports exactly. */
const checked = (data) => ({ own: data.own, passthrough: data.passthrough });

function serialise(data) {
  return `${JSON.stringify(data, null, 2)}\n`;
}

function main() {
  const check = process.argv.includes('--check');
  let data;
  try {
    data = generate();
  } catch (e) {
    console.error(`❌ ${e.message}`);
    process.exit(1);
  }
  const next = serialise(data);
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (check) {
    const stale =
      !prev ||
      JSON.stringify(checked(JSON.parse(prev))) !==
        JSON.stringify(checked(data));
    if (stale) {
      console.error(
        '❌ eslint/logician-exports.json is stale — logician-ui exports changed. Run `node scripts/eslint/generate-exports.cjs` and commit the result.'
      );
      process.exit(1);
    }
    console.log(
      `✅ eslint/logician-exports.json is up to date (${data.own.values.length + data.own.types.length} own, ${data.passthrough.values.length + data.passthrough.types.length} pass-through).`
    );
    return;
  }
  fs.writeFileSync(OUT, next);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}

if (require.main === module) main();

module.exports = { checked, generate, serialise, OUT };
